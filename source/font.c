static const Glyph *find_glyph(char c) {
    unsigned k;
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    for (k = 0; k < sizeof(GLYPHS) / sizeof(GLYPHS[0]); k++)
        if (GLYPHS[k].ch == c) return &GLYPHS[k];
    return NULL;
}

float text_width(const char *s, float scale) {
    int n = (int)strlen(s);
    return n > 0 ? (n * 6 - 1) * scale : 0;
}

static void draw_raw(float x, float y, const char *s, float sc, Col c) {
    for (; *s; s++, x += 6 * sc) {
        const Glyph *g = find_glyph(*s);
        int r;
        if (!g) continue;
        for (r = 0; r < 7; r++) {
            int k = 0;
            while (k < 5) {
                if (g->rows[r][k] == '#') {
                    int e = k;
                    while (e < 5 && g->rows[r][e] == '#') e++;
                    plat_rect(x + k * sc, y + r * sc, (e - k) * sc, sc, c);
                    k = e;
                } else k++;
            }
        }
    }
}

void text_draw(float x, float y, const char *s, float sc, Col c) {
    float o = sc * 0.5f < 1.0f ? 1.0f : sc * 0.5f;
    draw_raw(x + o, y + o, s, sc, cola(0, 0, 0, 170));
    draw_raw(x, y, s, sc, c);
}

void text_draw_center(float cx, float y, const char *s, float sc, Col c) {
    text_draw(cx - text_width(s, sc) * 0.5f, y, s, sc, c);
}

void text_draw_right(float rx, float y, const char *s, float sc, Col c) {
    text_draw(rx - text_width(s, sc), y, s, sc, c);
}
